#!/usr/bin/env ruby
# frozen_string_literal: true

# Generate src/node_kinds.inc, the SP_NODE_KINDS list of src/node_table.h (the
# node types nt_kind knows), from Prism's own node list, so that a node type
# Prism has is a node kind here and a PRISM_VERSION bump that adds one cannot
# leave it out.
#
#   ruby tools/gen_node_kinds.rb            # print the list
#   ruby tools/gen_node_kinds.rb --write    # regenerate src/node_kinds.inc
#   ruby tools/gen_node_kinds.rb --check    # fail when Prism has a node type
#                                           # the file lacks, the file names
#                                           # one Prism has not (and Spinel
#                                           # does not make), or it is stale
#                                           # (make node-kinds-check)
#
# The generated file is checked in, so a build needs no Ruby (the way
# src/value_pos_arms.inc is). --check reads the pinned Prism gem's
# vendor/prism/config.yml (PRISM_CONFIG names another), which `make deps`
# fetches and the repository does not keep; it is one of test-run's legs.
#
# The list is sorted by name, as nt_kind_resolve searches it with bsearch. The
# kinds below are Spinel's own: node types the compiler makes that Prism does
# not have.

require "yaml"
require "optparse"

ROOT = File.expand_path("..", __dir__)
CONFIG = ENV["PRISM_CONFIG"] || File.join(ROOT, "vendor/prism/config.yml")
OUTPUT = File.join(ROOT, "src/node_kinds.inc")

# name => what makes it (one short line, copied into the generated file)
OWN = {
  "UnsupportedNode" => "flatten's stand-in (spinel_parse.c) for a Prism node type it has no case for",
  "LoadNode" => "a require's load of its file's root under --load-model=graph (spinel_parse.c)",
}.freeze

def prism_nodes
  YAML.load_file(CONFIG).fetch("nodes").map { |n| n.fetch("name") }
end

def kinds(prism)
  (prism + OWN.keys).sort
end

def generate(prism)
  out = +"/* Generated by tools/gen_node_kinds.rb from Prism's config.yml: do not edit.\n"
  out << "   Every node type Prism has, sorted (nt_kind_resolve searches the list by\n"
  out << "   name), and the compiler's own:\n"
  OWN.each { |name, why| out << "     #{name}: #{why}\n" }
  out << "   make node-kinds-check fails when this file is stale. */\n"
  out << "#define SP_NODE_KINDS(X) \\\n"
  out << kinds(prism).map { |k| "  X(#{k})" }.join(" \\\n") << "\n"
  out
end

def check(prism, text)
  errors = []
  own = OWN.keys
  clash = own & prism
  errors << "#{clash.join(', ')} is Prism's own node type; drop it from OWN" unless clash.empty?
  if File.exist?(OUTPUT)
    have = File.read(OUTPUT).scan(/^\s+X\((\w+)\)/).flatten
    (prism - have).each { |k| errors << "Prism has #{k}, which src/node_kinds.inc lacks" }
    (have - prism - own).each { |k| errors << "src/node_kinds.inc names #{k}, which Prism does not have and OWN does not make" }
    errors << "src/node_kinds.inc is not sorted" unless have == have.sort
  else
    errors << "src/node_kinds.inc is missing"
  end
  errors << "src/node_kinds.inc is stale; regenerate with --write" unless File.exist?(OUTPUT) && File.read(OUTPUT) == text
  errors
end

opts = {}
OptionParser.new do |p|
  p.on("--write") { opts[:write] = true }
  p.on("--check") { opts[:check] = true }
end.parse!

prism = prism_nodes
text = generate(prism)

if opts[:check]
  errors = check(prism, text)
  if errors.empty?
    puts "node-kinds-check: ok (#{prism.size} Prism node types, #{OWN.size} of Spinel's own)"
  else
    warn errors.map { |m| "node-kinds-check: #{m}" }
    exit 1
  end
elsif opts[:write]
  File.write(OUTPUT, text)
  puts "wrote #{OUTPUT}"
else
  print text
end
