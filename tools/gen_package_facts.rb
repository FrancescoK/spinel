#!/usr/bin/env ruby
# frozen_string_literal: true

# Generate src/package_facts.inc, the facts about the pre-installed packages
# (packages/*/spin.toml) that the compiler reads, from the manifests
# themselves, so the package keeps them and the compiler holds no list:
#
#   boot = "<feature>"   CRuby has the feature loaded before a program runs
#                        (Set, IO::Buffer): a program that names what the
#                        package defines gets it without a require.
#   rides = "<require>"  the package is an add-on that `require "<require>"`
#                        makes available (CRuby's time.rb for "time", whose
#                        require stays the runtime's): it loads with that
#                        require when the program names what it defines.
#
#   ruby tools/gen_package_facts.rb            # print the rows
#   ruby tools/gen_package_facts.rb --write    # regenerate src/package_facts.inc
#   ruby tools/gen_package_facts.rb --check    # fail when the file is stale or a
#                                              # fact names a file the package
#                                              # lacks (make package-facts-check)
#
# The generated file is checked in, so a build needs no Ruby. The manifests
# are read with spin's own reader (tools/spin/toml.rb). A row is the package,
# the feature its file is required by (packages/<package>/<feature>.rb), and
# the two facts; packages with neither key have no row.

require "optparse"

ROOT = File.expand_path("..", __dir__)
OUTPUT = File.join(ROOT, "src/package_facts.inc")
load File.join(ROOT, "tools/spin/toml.rb")

def rows
  Dir[File.join(ROOT, "packages/*/spin.toml")].sort.filter_map do |path|
    doc = TomlDoc.parse(File.read(path))
    pkg = File.basename(File.dirname(path))
    boot = doc.get("package", "boot")
    rides = doc.get("package", "rides")
    next if boot.empty? && rides.empty?
    { package: pkg, feature: boot.empty? ? pkg : boot, boot: !boot.empty?, rides: rides }
  end
end

def c_str(s) = s.empty? ? "NULL" : "\"#{s}\""

def generate(rows)
  out = +"/* Generated by tools/gen_package_facts.rb from the packages' spin.toml: do not\n"
  out << "   edit. Each row: the package, the feature its file is required by\n"
  out << "   (packages/<package>/<feature>.rb), whether CRuby has it loaded at boot\n"
  out << "   (`boot`), and the require it rides as an add-on (`rides`), or NULL.\n"
  out << "   make package-facts-check fails when this file is stale. */\n"
  out << "#define SP_PACKAGE_FACTS(X) \\\n"
  out << rows.map { |r| "  X(\"#{r[:package]}\", \"#{r[:feature]}\", #{r[:boot] ? 1 : 0}, #{c_str(r[:rides])})" }.join(" \\\n") << "\n"
  out
end

def check(rows, text)
  errors = []
  rows.each do |r|
    file = File.join(ROOT, "packages", r[:package], "#{r[:feature]}.rb")
    errors << "#{r[:package]}: no #{file.delete_prefix(ROOT + '/')} for its feature #{r[:feature]}" unless File.exist?(file)
    errors << "#{r[:package]}: both boot and rides" if r[:boot] && !r[:rides].empty?
  end
  errors << "src/package_facts.inc is stale; regenerate with --write" unless File.exist?(OUTPUT) && File.read(OUTPUT) == text
  errors
end

opts = {}
OptionParser.new do |p|
  p.on("--write") { opts[:write] = true }
  p.on("--check") { opts[:check] = true }
end.parse!

rs = rows
text = generate(rs)

if opts[:check]
  errors = check(rs, text)
  if errors.empty?
    puts "package-facts-check: ok (#{rs.count { _1[:boot] }} at boot, #{rs.count { !_1[:rides].empty? }} add-on)"
  else
    warn errors.map { |m| "package-facts-check: #{m}" }
    exit 1
  end
elsif opts[:write]
  File.write(OUTPUT, text)
  puts "wrote #{OUTPUT}"
else
  print text
end
