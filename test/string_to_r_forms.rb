# spinel: int64 -- assumes a 64-bit Integer (values or arithmetic past 2^31); not run on a 32-bit target
# String#to_r reads digits with `_` between them, a fraction, an exponent and a
# denominator of the same form, and stops at the first byte that does not fit.
